// Redes digitales entre bloques Verilog (#209): una red que une sólo pines de bloques generados
// (la salida de uno y entradas de otros, nada más) no necesita pasar por lo analógico. Cada pin de
// un bloque es un puente (dac_bridge a la salida, bidi_bridge a la entrada) y la red entre los dos
// es un nodo de la matriz con rampas tr/tf: cada flanco achica el paso del transitorio. Acá esas
// redes se vuelven nodos de eventos de XSPICE: la instancia usa una copia de su .subckt sin los
// puentes de esos pines, con el nodo digital de adentro como puerto. Lo que se pierde es la rampa y
// el cruce del umbral (del orden de tr/2), que sin nada analógico en la red no se ve.
//
// Sólo se hace si es seguro: la red tiene exactamente una salida de dac_bridge (hdl_dac) y al
// menos una entrada (hdl_in), y no aparece en ninguna otra línea de la netlist (otro elemento, .meas, una fuente B, .control…).
// Las tri-state e inout (bidi_bridge de salida) siguen siendo analógicas.

const GENERATED = /^\* Generated by TurboSpice from /m;

interface Tok {
  text: string;
  start: number;
  end: number;
}

/** Palabras de una línea con su posición, sin cortar expresiones entre llaves o paréntesis */
function tokens(line: string): Tok[] {
  const out: Tok[] = [];
  let depth = 0;
  let start = -1;
  for (let i = 0; i <= line.length; i++) {
    const ch = line[i];
    if (ch === '{' || ch === '(') depth++;
    if (ch === '}' || ch === ')') depth = Math.max(0, depth - 1);
    const sep = ch === undefined || (/\s/.test(ch) && depth === 0);
    if (sep && start >= 0) {
      out.push({ text: line.slice(start, i), start, end: i });
      start = -1;
    } else if (!sep && start < 0) start = i;
  }
  return out;
}

interface PinInfo {
  /** 'out': dac_bridge desde el nodo de adentro; 'in': bidi_bridge de entrada; 'other': el resto */
  role: 'out' | 'in' | 'other';
  /** nodo digital de adentro */
  node?: string;
}

interface GenSubckt {
  file: string;
  name: string;
  pins: string[];
  header: string;
  body: string[];
  info: Map<string, PinInfo>;
}

/** Los .subckt generados de un Verilog que hay en los archivos de la simulación */
function generatedSubckts(files: Record<string, string>): Map<string, GenSubckt> {
  const out = new Map<string, GenSubckt>();
  for (const [file, text] of Object.entries(files)) {
    if (!GENERATED.test(text)) continue;
    const re = /^(\.subckt\s+(\S+)\s+[^\n]*)\n([\s\S]*?)^\.ends\b[^\n]*/gim;
    for (const m of text.matchAll(re)) {
      const header = m[1];
      const pins = header.split(/\s+/).slice(2).filter((p) => p && !p.includes('='));
      const body = m[3].split('\n').filter((l) => l.trim());
      const info = new Map<string, PinInfo>();
      for (const pin of pins) {
        const esc = pin.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        const line = body.find((l) => new RegExp(`^ab_${esc}\\s`, 'i').test(l));
        const out1 = line && new RegExp(`^ab_${esc}\\s+\\[(\\S+)\\]\\s+\\[${esc}\\]\\s+hdl_dac\\s*$`, 'i').exec(line);
        const in1 = line && new RegExp(`^ab_${esc}\\s+\\[${esc}\\]\\s+\\[(\\S+)\\]\\s+null\\s+hdl_in\\s*$`, 'i').exec(line);
        info.set(pin, out1 ? { role: 'out', node: out1[1] } : in1 ? { role: 'in', node: in1[1] } : { role: 'other' });
      }
      out.set(m[2].toLowerCase(), { file, name: m[2], pins, header, body, info });
    }
  }
  return out;
}

/**
 * Copia del .subckt con esos pines digitales: sin sus puentes, el nodo de adentro es el puerto. Si
 * varios de esos pines comparten el nodo (una entrada que sale tal cual: g[7] = b[7]), el nodo toma
 * el nombre de la entrada (o de la primera salida) y las otras salidas salen por un d_buffer.
 */
function digitalVariant(sub: GenSubckt, pins: Set<string>, name: string): string {
  const byNode = new Map<string, string[]>();
  for (const pin of pins) {
    const node = sub.info.get(pin)!.node!;
    byNode.set(node, [...(byNode.get(node) ?? []), pin]);
  }
  const rename = new Map<string, string>();
  const buffers: string[] = [];
  for (const [node, list] of byNode) {
    const port = list.find((p) => sub.info.get(p)!.role === 'in') ?? list[0];
    rename.set(node, port);
    for (const p of list) if (p !== port) buffers.push(`alnk_${p} ${port} ${p} hdl_lnk`);
  }
  const drop = new Set([...pins].map((p) => `ab_${p}`.toLowerCase()));
  const body = sub.body
    .filter((l) => !drop.has(l.trim().split(/\s+/)[0].toLowerCase()))
    .map((l) => l.replace(/[^\s[\]]+/g, (w) => rename.get(w) ?? w));
  const header = sub.header.replace(/^(\.subckt\s+)\S+/i, `$1${name}`);
  const model = buffers.length ? ['.model hdl_lnk d_buffer(rise_delay=1e-12 fall_delay=1e-12)'] : [];
  return [`* ${sub.name} with digital pins ${[...pins].join(' ')} (TurboSpice: nets between Verilog blocks)`, header, ...body, ...buffers, ...model, `.ends ${name}`, ''].join('\n');
}

const isGround = (n: string) => n === '0' || n.toLowerCase() === 'gnd';

/**
 * Pasa a digitales las redes entre bloques Verilog de la netlist (ver arriba). Devuelve la netlist
 * y los archivos cambiados, las redes que quedaron digitales (nombres de ngspice, en minúsculas) y
 * los nodos de adentro que desaparecieron ("x1.q_0_d") → su red.
 */
export function linkDigitalNets(
  netlist: string,
  files: Record<string, string>,
): { netlist: string; files: Record<string, string>; nets: string[]; aliases: Map<string, string> } {
  const aliases = new Map<string, string>();
  const subs = generatedSubckts(files);
  if (!subs.size) return { netlist, files, nets: [], aliases };
  const lines = netlist.split('\n');
  // instancias de nivel superior de los bloques generados
  interface Inst {
    line: number;
    name: string;
    sub: GenSubckt;
    nameTok: Tok;
    nodes: string[];
  }
  const insts: Inst[] = [];
  let depth = 0;
  let control = false;
  lines.forEach((l, i) => {
    const s = l.trim().toLowerCase();
    if (s.startsWith('.control')) control = true;
    if (s.startsWith('.endc')) control = false;
    if (s.startsWith('.subckt')) depth++;
    if (s.startsWith('.ends')) depth--;
    if (depth || control || !/^x/i.test(l.trim())) return;
    const tt = tokens(l);
    const pos: Tok[] = [];
    for (const t of tt) {
      if (/^params:/i.test(t.text)) break;
      if (!t.text.includes('=')) pos.push(t);
    }
    const nameTok = pos[pos.length - 1];
    const sub = nameTok && subs.get(nameTok.text.toLowerCase());
    if (!sub || pos.length - 2 !== sub.pins.length) return;
    insts.push({ line: i, name: pos[0].text, sub, nameTok, nodes: pos.slice(1, -1).map((t) => t.text) });
  });
  if (insts.length < 2) return { netlist, files, nets: [], aliases };

  // red → pines de bloques que la tocan
  const byNet = new Map<string, { inst: Inst; pin: string; role: PinInfo['role'] }[]>();
  for (const inst of insts)
    inst.nodes.forEach((n, k) => {
      const key = n.toLowerCase();
      if (isGround(key)) return;
      const pin = inst.sub.pins[k];
      byNet.set(key, [...(byNet.get(key) ?? []), { inst, pin, role: inst.sub.info.get(pin)!.role }]);
    });
  // cuántas veces aparece cada red en el resto de la netlist (sin comentarios ni la R de los flotantes)
  const instLines = new Set(insts.map((x) => x.line));
  const elsewhere = new Set<string>();
  lines.forEach((l, i) => {
    if (instLines.has(i) || /^\s*\*/.test(l) || /^\s*R__float\d+\s/i.test(l)) return;
    for (const w of l.toLowerCase().split(/[\s(),=[\]{}]+/)) if (byNet.has(w)) elsewhere.add(w);
  });

  const nets: string[] = [];
  /** instancia → pines que pasan a digitales */
  const digital = new Map<Inst, Set<string>>();
  for (const [net, uses] of byNet) {
    if (elsewhere.has(net)) continue;
    if (uses.some((u) => u.role === 'other')) continue;
    if (uses.filter((u) => u.role === 'out').length !== 1 || !uses.some((u) => u.role === 'in')) continue;
    nets.push(net);
    for (const u of uses) {
      digital.set(u.inst, (digital.get(u.inst) ?? new Set()).add(u.pin));
      // el nodo de adentro deja de existir: Dig(x1.q_0_d) de antes es ahora la red
      aliases.set(`${u.inst.name}.${u.inst.sub.info.get(u.pin)!.node}`.toLowerCase(), net);
    }
  }
  if (!nets.length) return { netlist, files, nets, aliases };

  // una copia del .subckt por combinación de pines digitales
  const variants = new Map<string, string>();
  const outFiles = { ...files };
  for (const [inst, pins] of digital) {
    const key = `${inst.sub.name.toLowerCase()}|${[...pins].sort().join(' ')}`;
    let name = variants.get(key);
    if (!name) {
      name = `${inst.sub.name}__dig${variants.size + 1}`;
      variants.set(key, name);
      outFiles[inst.sub.file] = `${outFiles[inst.sub.file].replace(/\n*$/, '\n')}${digitalVariant(inst.sub, pins, name)}`;
    }
    const l = lines[inst.line];
    lines[inst.line] = l.slice(0, inst.nameTok.start) + name + l.slice(inst.nameTok.end);
  }
  const set = new Set(nets);
  const out = lines
    // (una resistencia en un nodo digital es un error de ngspice)
    .filter((l) => !(/^\s*R__float\d+\s/i.test(l) && set.has(l.trim().split(/\s+/)[1]?.toLowerCase())))
    .map((l) => (/^\s*\.end\s*$/i.test(l) ? `* nets between Verilog blocks, digital (no bridges): ${nets.join(' ')}\n${l}` : l));
  return { netlist: out.join('\n'), files: outFiles, nets, aliases };
}
