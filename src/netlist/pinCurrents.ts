// Corriente en cada pin de las instancias de subcircuito (Ix(U1:OUT), como LTspice). ngspice no
// tiene corrientes por pin en un X: cada pin pasa por una fuente de 0 V en serie
// ("V__ix_x1_2 out x1__p2 0" y la X con x1__p2), cuya rama es la corriente que entra al pin.
// Se hace sobre la netlist ya armada, después de linkDigitalNets: los bloques Verilog (los
// .subckt generados) quedan como están, así sus redes digitales siguen enlazándose.

const GENERATED = /^\* Generated by TurboSpice from /m;

/** Nombre del pin k (1…) de la instancia `inst` (nombre de ngspice, como en la línea X) */
export const pinSourceName = (inst: string, k: number) => `v__ix_${inst.toLowerCase()}_${k}`;

/**
 * Vector con la corriente que entra al pin k (1…, SpiceOrder) de la instancia: `inst` es "x1" en el
 * nivel superior o "x.x_u1.x2" adentro de otra (como hierDevice)
 */
export function pinCurrentVector(inst: string, k: number): string {
  const n = inst.toLowerCase();
  const h = /^x\.(.+)\.([^.]+)$/.exec(n);
  return h ? `v.${h[1]}.${pinSourceName(h[2], k)}#branch` : `${pinSourceName(n, k)}#branch`;
}

/** Pin (1…) cuya fuente lleva la corriente del pin k: el primero en la misma red (ver abajo) */
export const sharedPin = (nodes: string[], k: number): number => nodes.findIndex((n) => n.toLowerCase() === nodes[k - 1]?.toLowerCase()) + 1 || k;

/** Palabras de una línea sin cortar expresiones entre llaves o paréntesis */
function words(line: string): string[] {
  const out: string[] = [];
  let depth = 0;
  let cur = '';
  for (const ch of `${line} `) {
    if (ch === '{' || ch === '(') depth++;
    if (ch === '}' || ch === ')') depth = Math.max(0, depth - 1);
    if (/\s/.test(ch) && depth === 0) {
      if (cur) out.push(cur);
      cur = '';
    } else cur += ch;
  }
  return out;
}

/** Agrega las fuentes de 0 V en los pines de las instancias X de la netlist (ver arriba) */
export function addPinCurrentSources(netlist: string, files: Record<string, string>): string {
  const generated = new Set<string>();
  for (const text of Object.values(files)) if (GENERATED.test(text)) for (const m of text.matchAll(/^\.subckt\s+(\S+)/gim)) generated.add(m[1].toLowerCase());
  const lines = netlist.split('\n');
  const out: string[] = [];
  let control = false;
  lines.forEach((l, i) => {
    const s = l.trim().toLowerCase();
    if (s.startsWith('.control')) control = true;
    if (s.startsWith('.endc')) control = false;
    // (una línea que sigue con "+" no se toca)
    if (control || !/^x/.test(s) || /^\s*\+/.test(lines[i + 1] ?? '')) return void out.push(l);
    const w = words(l.trim());
    let end = w.findIndex((x, k) => k > 0 && (/^params:/i.test(x) || x.includes('=')));
    if (end < 0) end = w.length;
    const nodes = w.slice(1, end - 1);
    const sub = w[end - 1];
    if (!nodes.length || !sub || generated.has(sub.toLowerCase())) return void out.push(l);
    const inst = w[0].toLowerCase();
    // varios pines en la misma red pasan por una sola fuente (la del primero): con una por pin,
    // si el modelo los une por dentro (dos GND, un amperímetro de 0 V) quedarían fuentes en
    // paralelo y la matriz, singular. Su corriente es la suma de esos pines.
    const first = new Map<string, number>();
    nodes.forEach((n, k) => first.has(n.toLowerCase()) || first.set(n.toLowerCase(), k));
    const inner = nodes.map((n) => `${inst}__p${first.get(n.toLowerCase())! + 1}`);
    nodes.forEach((n, k) => first.get(n.toLowerCase()) === k && out.push(`${pinSourceName(inst, k + 1)} ${n} ${inner[k]} 0`));
    out.push([w[0], ...inner, ...w.slice(end - 1)].join(' '));
  });
  return out.join('\n');
}
