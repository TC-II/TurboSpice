// Comparación de netlists estilo LTspice: idénticas, o equivalentes salvo el nombre de
// las redes sin etiqueta (N001, NC_01…), que se comparan como una biyección.
import { readFileSync } from 'node:fs';

/** Lee una .net de LTspice: UTF-8, o UTF-16LE si hace falta */
export function readNet(path) {
  const b = new Uint8Array(readFileSync(path));
  const utf16 = (b[0] === 0xff && b[1] === 0xfe) || (b.length > 3 && b[1] === 0 && b[3] === 0);
  return new TextDecoder(utf16 ? 'utf-16le' : 'utf-8').decode(b);
}

/** Saca de la salida de LTspice lo que depende de la máquina */
export function normalizeLtspice(text) {
  return text
    .split(/\r?\n/)
    .filter((l) => !/^\* (.:\\|Z:\\|\/)/.test(l) && !l.startsWith('* Generated by LTspice'))
    .map((l) => l.replace(/^\.lib .*[\\/]lib[\\/]cmp[\\/](standard\.\w+)$/i, '.lib $1'))
    .join('\n')
    .trim();
}

const AUTO_NODE = /^(N\d{3,}|NC_\d+|MP_\d+)$/;

export function compareNetlists(ref, ours) {
  const a = ref.trim().split('\n');
  const b = ours.trim().split('\n');
  if (a.join('\n') === b.join('\n')) return { exact: true, equivalent: true };
  if (a.length !== b.length) {
    const i = a.findIndex((l, k) => l !== b[k]);
    return { exact: false, equivalent: false, reason: `distinta cantidad de líneas (${a.length} vs ${b.length}); primera diferencia línea ${i + 1}:\n        LT: ${a[i]}\n        TS: ${b[i]}` };
  }
  // Equivalencia: mismos tokens salvo nodos automáticos, con un mapeo consistente
  const map = new Map();
  const rev = new Map();
  for (let i = 0; i < a.length; i++) {
    const ta = a[i].split(' ');
    const tb = b[i].split(' ');
    const fail = (why) => ({ exact: false, equivalent: false, reason: `línea ${i + 1} (${why}):\n        LT: ${a[i]}\n        TS: ${b[i]}` });
    if (ta.length !== tb.length) return fail('tokens');
    for (let j = 0; j < ta.length; j++) {
      if (ta[j] === tb[j] && !AUTO_NODE.test(ta[j])) continue;
      if (!AUTO_NODE.test(ta[j]) || !AUTO_NODE.test(tb[j])) return fail(`"${ta[j]}" vs "${tb[j]}"`);
      if ((map.has(ta[j]) && map.get(ta[j]) !== tb[j]) || (rev.has(tb[j]) && rev.get(tb[j]) !== ta[j])) {
        return fail(`mapeo de nodos inconsistente ${ta[j]}↔${tb[j]}`);
      }
      map.set(ta[j], tb[j]);
      rev.set(tb[j], ta[j]);
    }
  }
  return { exact: false, equivalent: true };
}
