// Redes entre bloques Verilog simuladas digitales, sin puentes (#209)
import { describe, expect, it } from 'vitest';
import { linkDigitalNets } from '../../src/hdl/digitalLinks.ts';

const GEN = '* Generated by TurboSpice from X.v (Yosys): edit the Verilog, not this file';
const A = [
  GEN,
  '.subckt A clk q t vcc=5',
  'ab_clk [clk] [clk_d] null hdl_in',
  'ab_q [q_d] [q] hdl_dac',
  'ab_t [t] [t_d] null hdl_out',
  'rleak_t t 0 1g',
  'af1 q_d clk_d null null q_d null hdl_dff0',
  'at1 q_d clk_d t_d hdl_tbuf',
  '.model hdl_dac dac_bridge(out_low={vol})',
  '.ends A',
  '',
].join('\n');
const B = [GEN, '.subckt B d y vcc=5', 'ab_d [d] [d_d] null hdl_in', 'ab_y [y_d] [y] hdl_dac', 'ag1 d_d y_d hdl_inv', '.ends B', ''].join('\n');
const files = { 'project/a.sub': A, 'project/b.sub': B };
const net = (...body: string[]) => ['* t', ...body, '.include project/a.sub', '.include project/b.sub', '.end'].join('\n');

describe('redes entre bloques Verilog, digitales', () => {
  it('una salida que sólo va a entradas de otros bloques: sin puentes y sin la R de los flotantes', () => {
    const r = linkDigitalNets(net('X1 clk q t A vcc=5', 'X2 q y B vcc={v}', 'X3 q y2 B', 'Vclk clk 0 PULSE(0 5 0 1n 1n 5n 10n)', 'R1 y 0 1k', 'R2 y2 0 1k', 'R__float1 q 0 1e12'), files);
    expect(r.nets).toEqual(['q']);
    expect(r.netlist).toContain('X1 clk q t A__dig1 vcc=5');
    expect(r.netlist).toContain('X2 q y B__dig2 vcc={v}');
    // las dos instancias de B usan la misma copia
    expect(r.netlist).toContain('X3 q y2 B__dig2');
    expect(r.netlist).not.toContain('R__float1');
    const a = r.files['project/a.sub'];
    expect(a).toContain('.subckt A clk q t vcc=5');
    const dig = a.slice(a.indexOf('.subckt A__dig1'));
    expect(dig).not.toMatch(/^ab_q /m);
    // el nodo de adentro es el puerto; los otros pines siguen con su puente
    expect(dig).toContain('af1 q clk_d null null q null hdl_dff0');
    expect(dig).toContain('ab_clk [clk] [clk_d] null hdl_in');
    expect(r.files['project/b.sub']).toContain('ag1 d y_d hdl_inv');
    // los nodos de adentro que desaparecen, para las trazas Dig() de antes
    expect([...r.aliases]).toEqual([['x1.q_d', 'q'], ['x2.d_d', 'q'], ['x3.d_d', 'q']]);
  });

  it('si la red toca algo más (un elemento, una fuente B, .meas) queda analógica', () => {
    for (const extra of ['R1 q 0 1k', 'B1 o 0 V=V(q)*2', '.meas tran m max V(q)']) expect(linkDigitalNets(net('X1 clk q t A', 'X2 q y B', extra), files).nets).toEqual([]);
  });

  it('sin entradas que la lean, con dos salidas o con una tri-state, también', () => {
    // sólo la salida de X1
    expect(linkDigitalNets(net('X1 clk q t A', 'X2 d y B'), files).nets).toEqual([]);
    // dos salidas en la misma red
    expect(linkDigitalNets(net('X1 clk n t A', 'X2 d n B', 'X3 n y B'), files).nets).toEqual([]);
    // la salida tri-state (bidi_bridge) de X1
    expect(linkDigitalNets(net('X1 clk q t A', 'X2 t y B'), files).nets).toEqual([]);
  });

  it('una entrada que sale tal cual (g[7] = b[7]): el nodo es la entrada y la salida sale por un buffer', () => {
    const P = [GEN, '.subckt P b g vcc=5', 'ab_b [b] [b_d] null hdl_in', 'ab_g [b_d] [g] hdl_dac', '.ends P', ''].join('\n');
    const fs = { ...files, 'project/p.sub': P };
    const r = linkDigitalNets(['* t', 'X1 clk q t A', 'X2 q y P', 'X3 y z B', 'R1 z 0 1k', '.end'].join('\n'), fs);
    expect(r.nets.sort()).toEqual(['q', 'y']);
    const p = r.files['project/p.sub'];
    const dig = p.slice(p.indexOf('.subckt P__dig'));
    expect(dig).not.toMatch(/^ab_/m);
    expect(dig).toContain('alnk_g b g hdl_lnk');
    expect(dig).toContain('.model hdl_lnk d_buffer');
  });

  it('un subcircuito que no generó TurboSpice no se toca', () => {
    const other = { 'lib/c.sub': '.subckt C a b\nab_a [a_d] [a] hdl_dac\nab_b [b] [b_d] null hdl_in\n.ends C\n' };
    const text = ['* t', 'X1 n 1 C', 'X2 2 n C', '.end'].join('\n');
    expect(linkDigitalNets(text, other)).toEqual({ netlist: text, files: other, nets: [], aliases: new Map() });
  });
});
