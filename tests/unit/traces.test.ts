// Corrientes de la punta de prueba en componentes de varios pines (#53)
import { describe, expect, it } from 'vitest';
import { DIGITAL_TYPE, type SimPlot } from '../../src/engine/ngspice.ts';
import type { BuiltSimulation } from '../../src/sim/schematicSim.ts';
import { addPinCurrentSources } from '../../src/netlist/pinCurrents.ts';
import { digitalProbeExpr, multiPinPrefix, probeExpr, traceResolver, verilogDigitalNode } from '../../src/sim/traces.ts';

const sim = {
  lt: {
    elements: [
      { name: 'M1', prefix: 'MN', sym: 0 },
      { name: 'Q1', prefix: 'QN', sym: 1 },
      { name: 'R1', prefix: 'R', sym: 2 },
    ],
  },
  ng: {
    names: new Map([
      ['M1', 'm1'],
      ['Q1', 'q1'],
      ['R1', 'r1'],
    ]),
  },
} as unknown as BuiltSimulation;

const vec = (name: string, v: number) => ({ name, type: 0, real: Float64Array.of(v, v) });
const plot: SimPlot = {
  name: 'tran1',
  vectors: [
    { name: 'time', type: 1, real: Float64Array.of(0, 1) },
    vec('@m1[id]', 1),
    vec('@m1[ig]', 2),
    vec('@m1[is]', -1),
    vec('@m1[ib]', 3),
    vec('@q1[ic]', 4),
    vec('@q1[ib]', 5),
    vec('@q1[ie]', 6),
    vec('@r1[i]', 7),
  ],
};

describe('punta de prueba en transistores', () => {
  it('cada pin mide su corriente (orden SpiceOrder: D G S B, C B E)', () => {
    expect([1, 2, 3, 4].map((pin) => probeExpr(sim, { symbol: 0, pin }))).toEqual(['Id(M1)', 'Ig(M1)', 'Is(M1)', 'Ib(M1)']);
    expect([1, 2, 3].map((pin) => probeExpr(sim, { symbol: 1, pin }))).toEqual(['Ic(Q1)', 'Ib(Q1)', 'Ie(Q1)']);
    expect(probeExpr(sim, { symbol: 2 })).toBe('I(R1)');
  });

  it('Id, Ig, Ic… se resuelven con las corrientes que guarda ngspice', () => {
    const r = traceResolver(sim, plot);
    const at = (fn: string, el: string) => r(fn, [el])?.re[0];
    expect([at('Id', 'M1'), at('Ig', 'M1'), at('Is', 'M1'), at('Ib', 'M1')]).toEqual([1, 2, -1, 3]);
    expect([at('Ic', 'Q1'), at('Ib', 'Q1'), at('Ie', 'Q1')]).toEqual([4, 5, 6]);
    expect(at('I', 'R1')).toBe(7);
  });

  it('MOS, BJT, JFET y subcircuitos son de varios pines', () => {
    expect(['MN', 'MP', 'QN', 'QP', 'JN', 'JP', 'X'].every(multiPinPrefix)).toBe(true);
    expect(['R', 'C', 'L', 'D', 'V'].some(multiPinPrefix)).toBe(false);
  });
});

describe('corriente en los pines de un subcircuito: Ix(U1:OUT)', () => {
  const xsim = {
    lt: { elements: [{ name: 'U1', prefix: 'X', sym: 0, nodes: ['inp', 'inn', 'vcc', 'vee', 'out'], pinNames: ['In+', 'In-', 'V+', 'V-', 'OUT'] }] },
    ng: { names: new Map([['U1', 'XU1']]) },
  } as unknown as BuiltSimulation;
  const xplot: SimPlot = { name: 'op1', vectors: [vec('v__ix_xu1_5#branch', -2e-3), vec('v.x_a.v__ix_xb_2#branch', 3)] };

  it('la punta de prueba en un pin mide Ix con el nombre del pin', () => {
    expect(probeExpr(xsim, { symbol: 0, pin: 5 })).toBe('Ix(U1:OUT)');
  });

  it('se lee de la fuente de 0 V en serie con el pin, por nombre o número', () => {
    const r = traceResolver(xsim, xplot);
    expect(r('Ix', ['U1:out'])?.re[0]).toBe(-2e-3);
    expect(r('Ix', ['U1:5'])?.re[0]).toBe(-2e-3);
    expect(r('Ix', ['x_a.xb:2'])?.re[0]).toBe(3);
  });

  it('la netlist lleva una fuente por pin, salvo en los bloques Verilog', () => {
    const net = ['* t', 'XU1 inp inn vcc vee out opamp params: a=1', 'XV1 a b ENC', '.control', 'x1 a b', '.endc', '.end'].join('\n');
    const files = { 'enc.lib': '* Generated by TurboSpice from ENC.v (Yosys)\n.subckt ENC a b\n.ends' };
    const out = addPinCurrentSources(net, files).split('\n');
    expect(out).toContain('v__ix_xu1_1 inp xu1__p1 0');
    expect(out).toContain('v__ix_xu1_5 out xu1__p5 0');
    expect(out).toContain('XU1 xu1__p1 xu1__p2 xu1__p3 xu1__p4 xu1__p5 opamp params: a=1');
    expect(out).toContain('XV1 a b ENC');
    expect(out).toContain('x1 a b');
  });
});

describe('punta de prueba en la salida de un bloque Verilog (#209)', () => {
  const sub = [
    '* Generated by TurboSpice from ENC.v (Yosys): edit the Verilog, not this file',
    '.subckt ENC clk t1 d_1 d_0 y vcc=5 vil=2.5',
    'ab_clk [clk] [clk_d] null hdl_in',
    'ab_t1 [t1] [t1_d] null hdl_in',
    'ab_d_1 [d_1_d] [d_1] hdl_dac',
    'ab_d_0 [d_0_d] [d_0] hdl_dac',
    'ab_y [y] [n7] null hdl_out',
    '.ends ENC',
  ].join('\n');
  const vsim = {
    files: { 'project/enc.sub': sub, 'TCLib/x.lib': '.subckt ENC a b c d e\nab_d_1 [q] [d_1] hdl_dac\n.ends' },
    lt: { elements: [{ name: 'X1', prefix: 'X', sym: 0, value: 'ENC vcc=5', nodes: ['clk', 'in1', 'd[1]', 'd[0]', 'oe'] }] },
    ng: { names: new Map([['X1', 'X1']]) },
  } as unknown as BuiltSimulation;
  it('una salida da su nodo digital, una entrada no', () => {
    expect(verilogDigitalNode(vsim, 'd[0]')).toBe('x1.d_0_d');
    expect(verilogDigitalNode(vsim, 'OE')).toBe('x1.n7');
    expect(verilogDigitalNode(vsim, 'clk')).toBeNull();
    expect(verilogDigitalNode(vsim, 'otra')).toBeNull();
  });
  it('un bit es Dig(); los bits de un puerto, el bus entero', () => {
    // con el nombre del cable, no el nodo de adentro del bloque
    expect(digitalProbeExpr(vsim, ['d[1]'])).toBe('Dig(d[1])');
    expect(digitalProbeExpr(vsim, ['d[1]', 'd[0]'])).toBe('Dig(d[1:0])');
    expect(digitalProbeExpr(vsim, ['d[0]', 'd[1]'])).toBe('Dig(d[0:1])');
    expect(digitalProbeExpr(vsim, ['d[1]', 'd[0]'], 'bus[1:0]')).toBe('Dig(bus[1:0])');
    // con un bit que no sale del bloque, la tensión de siempre
    expect(digitalProbeExpr(vsim, ['d[1]', 'clk'])).toBeNull();
  });
  it('el resolver lleva el nombre del cable al nodo del bloque', () => {
    const dig = (name: string, v: number) => ({ name, type: DIGITAL_TYPE, real: Float64Array.of(v), x: Float64Array.of(0) });
    const plot = { name: 'tran1', vectors: [{ name: 'time', type: 1, real: Float64Array.of(0, 1) }, dig('x1.d_1_d', 1), dig('x1.d_0_d', 0)] } as unknown as SimPlot;
    const r = traceResolver(vsim, plot);
    expect(r('Dig', ['d[1]'])?.re[0]).toBe(1);
    expect(r('Dig', ['d[1:0]'])?.re[0]).toBe(2);
    expect(r('Dig', ['x1.d_1_d'])?.re[0]).toBe(1);
  });
});
